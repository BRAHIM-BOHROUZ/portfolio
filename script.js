let currentLanguage = "fr";

function setLanguage(language) {
    const selectedLanguage = translations[language] ? language : "fr";
    const content = translations[selectedLanguage];
    currentLanguage = selectedLanguage;

    document.documentElement.lang = selectedLanguage;
    document.documentElement.dir = selectedLanguage === "ar" ? "rtl" : "ltr";
    document.querySelectorAll("[data-i18n]").forEach(element => {
        const translation = content[element.dataset.i18n];
        if (!translation) return;

        const textNode = Array.from(element.childNodes).find(node =>
            node.nodeType === Node.TEXT_NODE && node.textContent.trim()
        );
        if (textNode) {
            const leadingSpace = textNode.textContent.match(/^\s*/)[0];
            const trailingSpace = textNode.textContent.match(/\s*$/)[0];
            textNode.textContent = `${leadingSpace}${translation}${trailingSpace}`;
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
        element.placeholder = content[element.dataset.i18nPlaceholder];
    });
    document.querySelectorAll("[data-i18n-title]").forEach(element => {
        element.title = content[element.dataset.i18nTitle];
    });

    document.title = content.pageTitle;
    document.querySelector('meta[name="description"]').content = content.pageDescription;
    document.querySelectorAll(".lang-btn").forEach(button => {
        button.classList.toggle("active", button.id === `lang-${selectedLanguage}`);
    });
    localStorage.setItem("selectedLanguage", selectedLanguage);
    updateThemeToggleLabel();
}

function updateThemeToggleLabel() {
    const theme = document.documentElement.dataset.theme || "dark";
    const switchLabel = translations[currentLanguage][theme === "dark" ? "theme.toLight" : "theme.toDark"];
    const themeToggle = document.getElementById("theme-toggle");

    themeToggle.setAttribute("aria-label", switchLabel);
    themeToggle.title = switchLabel;
}

function setTheme(theme) {
    const selectedTheme = theme === "light" ? "light" : "dark";
    const themeToggle = document.getElementById("theme-toggle");

    document.documentElement.dataset.theme = selectedTheme;
    themeToggle.innerHTML = `<i class="fa-solid ${selectedTheme === "dark" ? "fa-sun" : "fa-moon"}" aria-hidden="true"></i>`;
    updateThemeToggleLabel();
    localStorage.setItem("selectedTheme", selectedTheme);
}

const networkCanvas = document.querySelector(".network-canvas");
const networkContext = networkCanvas.getContext("2d");
const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
let networkNodes = [];
let networkWidth = 0;
let networkHeight = 0;
let networkAnimationFrame;

function drawNetwork() {
    const primaryColor = getComputedStyle(document.documentElement).getPropertyValue("--primary-color").trim();
    const accentColor = getComputedStyle(document.documentElement).getPropertyValue("--accent-color").trim();
    const maxDistance = 150;

    networkContext.clearRect(0, 0, networkWidth, networkHeight);

    networkNodes.forEach((node, index) => {
        if (!reducedMotion.matches) {
            node.x += node.vx;
            node.y += node.vy;
            if (node.x < 0 || node.x > networkWidth) node.vx *= -1;
            if (node.y < 0 || node.y > networkHeight) node.vy *= -1;
        }

        for (let nextIndex = index + 1; nextIndex < networkNodes.length; nextIndex++) {
            const nextNode = networkNodes[nextIndex];
            const distance = Math.hypot(node.x - nextNode.x, node.y - nextNode.y);
            if (distance < maxDistance) {
                networkContext.globalAlpha = (1 - distance / maxDistance) * 0.55;
                networkContext.strokeStyle = accentColor;
                networkContext.lineWidth = 1;
                networkContext.beginPath();
                networkContext.moveTo(node.x, node.y);
                networkContext.lineTo(nextNode.x, nextNode.y);
                networkContext.stroke();
            }
        }

        networkContext.globalAlpha = 0.85;
        networkContext.fillStyle = index % 3 === 0 ? accentColor : primaryColor;
        networkContext.beginPath();
        networkContext.arc(node.x, node.y, index % 4 === 0 ? 2 : 1.4, 0, Math.PI * 2);
        networkContext.fill();
    });

    networkContext.globalAlpha = 1;
    if (!reducedMotion.matches) networkAnimationFrame = requestAnimationFrame(drawNetwork);
}

function resizeNetworkCanvas() {
    const bounds = networkCanvas.getBoundingClientRect();
    const pixelRatio = Math.min(window.devicePixelRatio || 1, 2);
    networkWidth = bounds.width;
    networkHeight = bounds.height;
    networkCanvas.width = Math.round(networkWidth * pixelRatio);
    networkCanvas.height = Math.round(networkHeight * pixelRatio);
    networkContext.setTransform(pixelRatio, 0, 0, pixelRatio, 0, 0);

    const nodeCount = Math.min(70, Math.max(24, Math.round(networkWidth * networkHeight / 18000)));
    networkNodes = Array.from({ length: nodeCount }, () => ({
        x: Math.random() * networkWidth,
        y: Math.random() * networkHeight,
        vx: (Math.random() - 0.5) * 0.45,
        vy: (Math.random() - 0.5) * 0.45
    }));

    if (reducedMotion.matches) drawNetwork();
}

window.addEventListener("resize", resizeNetworkCanvas);
reducedMotion.addEventListener("change", () => {
    cancelAnimationFrame(networkAnimationFrame);
    drawNetwork();
});
resizeNetworkCanvas();
if (!reducedMotion.matches) drawNetwork();

