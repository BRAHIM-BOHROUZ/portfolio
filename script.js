const navigationToggle = document.querySelector(".nav-toggle");
const navigationMenu = document.getElementById("main-navigation");

navigationToggle.addEventListener("click", () => {
    const isOpen = navigationToggle.getAttribute("aria-expanded") === "true";
    navigationToggle.setAttribute("aria-expanded", String(!isOpen));
    navigationToggle.setAttribute("aria-label", isOpen ? "Ouvrir le menu" : "Fermer le menu");
    navigationToggle.innerHTML = `<i class="fa-solid ${isOpen ? "fa-bars" : "fa-xmark"}" aria-hidden="true"></i>`;
    navigationMenu.classList.toggle("is-open", !isOpen);
});

navigationMenu.querySelectorAll("a").forEach(link => {
    link.addEventListener("click", () => {
        navigationToggle.setAttribute("aria-expanded", "false");
        navigationToggle.setAttribute("aria-label", "Ouvrir le menu");
        navigationToggle.innerHTML = '<i class="fa-solid fa-bars" aria-hidden="true"></i>';
        navigationMenu.classList.remove("is-open");
    });
});

